/**
 * Function index:
 * - CashRegisterPanel: balances per account and per currency, a movement history, and (for finance.manage) the forms.
 *
 * A cash-CONTROL register of declared movements, not an accounting ledger: payments, refunds, expenses and payroll do
 * not move these balances, and nothing is reconciled with a bank. The page says so and links to the read-only cash
 * position report instead of netting the two.
 */
import Link from "next/link";

import { ArchiveButton, MovementForm, NewAccountForm, ReverseForm } from "@/components/cash-register-forms";
import {
  ACCOUNT_KIND_LABELS, groupBalancesByCurrency, KIND_LABELS, SOURCE_LABELS, type CashRegister,
} from "@/lib/cash-register";

function money(value: number, currency: string): string {
  try {
    return new Intl.NumberFormat("id-ID", { style: "currency", currency, maximumFractionDigits: currency === "IDR" ? 0 : 2 }).format(value);
  } catch {
    return `${currency} ${value.toLocaleString("id-ID")}`;
  }
}

export function CashRegisterPanel({ register, canManage, canCreateOrgWide, branches, today, requestKeys, error, nextHref }: {
  register: CashRegister | null;
  canManage: boolean;
  canCreateOrgWide: boolean;
  branches: ReadonlyArray<{ id: string; name: string }>;
  today: string;
  /** Idempotency keys generated by the server for this render (one for the movement form, one per reversible row). */
  requestKeys: { movement: string; reversals: Record<string, string> };
  error: string | null;
  nextHref: string | null;
}) {
  const accountName = new Map((register?.accounts ?? []).map((account) => [account.id, account.name]));
  const branchName = new Map(branches.map((branch) => [branch.id, branch.name]));
  const totals = register ? groupBalancesByCurrency(register.accounts) : [];
  return (
    <div className="mt-6 space-y-6">
      <p className="rounded-2xl border border-amber-200 bg-amber-50 p-4 text-xs leading-5 text-amber-900">
        Ini register kontrol kas, bukan buku besar akuntansi. Saldo = mutasi yang dicatat di sini (saldo awal, modal, penarikan, kas masuk/keluar lain). Pembayaran, refund, pengeluaran, dan payroll <strong>tidak</strong> mengubah saldo ini secara otomatis, dan tidak ada rekonsiliasi dengan rekening bank. Tautan ke pembayaran/pengeluaran/refund hanya referensi. Mata uang tidak pernah dijumlahkan.
        {" "}Laporan arus pembayaran, refund, dan pengeluaran ada di <Link href="/finance" className="font-bold underline">Posisi kas</Link>; keduanya sengaja tidak digabung.
      </p>
      {error ? <p role="alert" className="rounded-xl bg-rose-50 p-4 text-sm font-semibold text-rose-700">{error}</p> : null}

      <section aria-label="Saldo register" className="rounded-3xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6">
        <h2 className="font-bold">Saldo per akun</h2>
        {register === null ? null : register.accounts.length === 0 ? (
          <p className="mt-3 rounded-lg bg-slate-50 p-4 text-xs text-slate-500">Belum ada akun kas yang dapat Anda lihat.{canManage ? " Buat akun pertama di bawah." : ""}</p>
        ) : <>
          <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
            {totals.map((total) => (
              <div key={total.currency} className="rounded-2xl border border-slate-100 bg-slate-50 p-4">
                <p className="text-[11px] font-bold uppercase tracking-wide text-slate-400">{total.currency} · {total.accounts} akun</p>
                <p className={`mt-1 text-xl font-bold ${total.balance < 0 ? "text-rose-700" : "text-slate-900"}`}>{money(total.balance, total.currency)}</p>
              </div>
            ))}
          </div>
          <div className="mt-5 overflow-x-auto">
            <table className="w-full min-w-[640px] text-left text-xs">
              <thead className="text-[11px] uppercase text-slate-400"><tr><th className="py-2 pr-3">Akun</th><th className="pr-3">Jenis</th><th className="pr-3">Cabang</th><th className="pr-3 text-right">Masuk</th><th className="pr-3 text-right">Keluar</th><th className="pr-3 text-right">Saldo</th><th className="text-right">Terakhir</th>{canManage ? <th /> : null}</tr></thead>
              <tbody className="divide-y divide-slate-100">
                {register.accounts.map((account) => (
                  <tr key={account.id} className={account.status === "archived" ? "text-slate-400" : ""}>
                    <td className="py-2 pr-3 font-semibold">{account.name} <span className="text-slate-400">({account.currency})</span>{account.status === "archived" ? <span className="ml-2 rounded bg-slate-100 px-1.5 py-0.5 text-[10px] font-bold">arsip</span> : null}</td>
                    <td className="pr-3">{ACCOUNT_KIND_LABELS[account.kind]}</td>
                    <td className="pr-3">{account.branchId ? branchName.get(account.branchId) ?? "Cabang" : "Semua cabang"}</td>
                    <td className="pr-3 text-right">{money(account.totalIn, account.currency)}</td>
                    <td className="pr-3 text-right">{money(account.totalOut, account.currency)}</td>
                    <td className={`pr-3 text-right font-bold ${account.balance < 0 ? "text-rose-700" : ""}`}>{money(account.balance, account.currency)}</td>
                    <td className="text-right">{account.lastMovementOn ?? "—"}</td>
                    {canManage ? <td className="text-right"><ArchiveButton account={account} /></td> : null}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>}
      </section>

      {canManage ? (
        <section aria-label="Kelola register" className="grid gap-6 lg:grid-cols-1">
          <div className="rounded-3xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6">
            <h2 className="font-bold">Akun kas baru</h2>
            <p className="mt-1 text-xs text-slate-500">Maksimal 20 akun aktif. Mata uang dan cabang ditetapkan saat dibuat. Akun diarsipkan hanya saat saldonya nol.</p>
            <div className="mt-4"><NewAccountForm branches={branches} canCreateOrgWide={canCreateOrgWide} /></div>
          </div>
          <div className="rounded-3xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6">
            <h2 className="font-bold">Catat mutasi</h2>
            <p className="mt-1 text-xs text-slate-500">Mutasi tidak dapat diubah atau dihapus. Salah catat? Gunakan “Balik” pada riwayat; pembalikan adalah mutasi baru dengan alasan.</p>
            <div className="mt-4"><MovementForm accounts={register?.accounts ?? []} initialKey={requestKeys.movement} today={today} /></div>
          </div>
        </section>
      ) : <p className="rounded-xl border border-slate-200 bg-slate-50 p-4 text-xs text-slate-600">Peran Anda dapat melihat register, tetapi tidak memiliki finance.manage untuk mencatat atau membalik mutasi.</p>}

      <section aria-label="Riwayat mutasi" className="rounded-3xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6">
        <h2 className="font-bold">Riwayat mutasi</h2>
        {register === null ? null : register.movements.length === 0 ? <p className="mt-3 rounded-lg bg-slate-50 p-4 text-xs text-slate-500">Belum ada mutasi.</p> : (
          <div className="mt-4 overflow-x-auto">
            <table className="w-full min-w-[720px] text-left text-xs">
              <thead className="text-[11px] uppercase text-slate-400"><tr><th className="py-2 pr-3">Tanggal</th><th className="pr-3">Akun</th><th className="pr-3">Jenis</th><th className="pr-3 text-right">Jumlah</th><th className="pr-3">Pihak / catatan</th><th className="pr-3">Sumber</th>{canManage ? <th /> : null}</tr></thead>
              <tbody className="divide-y divide-slate-100">
                {register.movements.map((movement) => {
                  const reversed = register.reversed.has(movement.id);
                  return (
                    <tr key={movement.id} className={reversed ? "text-slate-400" : ""}>
                      <td className="py-2 pr-3">{movement.occurredOn}</td>
                      <td className="pr-3">{accountName.get(movement.accountId) ?? "Akun"}</td>
                      <td className="pr-3">{KIND_LABELS[movement.kind]}{reversed ? <span className="ml-2 rounded bg-slate-100 px-1.5 py-0.5 text-[10px] font-bold">dibalik</span> : null}</td>
                      <td className={`pr-3 text-right font-bold ${movement.direction === "out" ? "text-rose-700" : "text-emerald-700"}`}>{movement.direction === "out" ? "−" : "+"}{money(movement.amount, movement.currency)}</td>
                      <td className="max-w-[16rem] truncate pr-3">{[movement.counterparty, movement.memo].filter(Boolean).join(" · ") || "—"}</td>
                      <td className="pr-3">{movement.sourceType ? <span title={movement.sourceId ?? undefined}>{SOURCE_LABELS[movement.sourceType]}</span> : "—"}</td>
                      {canManage ? <td className="text-right">{movement.kind !== "reversal" && !reversed ? <ReverseForm movementId={movement.id} initialKey={requestKeys.reversals[movement.id] ?? ""} today={today} /> : null}</td> : null}
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
        {nextHref ? <div className="mt-4 text-center"><Link href={nextHref} className="rounded-lg border border-slate-200 bg-white px-4 py-2 text-xs font-bold text-slate-700">Muat lebih banyak</Link></div> : null}
      </section>
    </div>
  );
}
